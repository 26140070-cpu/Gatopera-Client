    private I18n() {
    }

    public static void setLanguage(Language language) {
        if (language == null) {
            language = Language.EN_US;
        }
        current = language;
        if (Gatopera.CONFIG != null) {
            Gatopera.CONFIG.settingsPut("language", language.getCode());
        }
        if (ClientSetting.INSTANCE != null && ClientSetting.INSTANCE.language != null) {
            ClientSetting.INSTANCE.language.setEnumValue(language.name());
        }
    }

    public static Language getLanguage() {
        return current;
    }

    public static void loadFromConfig() {
        if (Gatopera.CONFIG == null) {
            return;
        }
        current = Language.fromCode(Gatopera.CONFIG.getString("language", Language.EN_US.getCode()));
    }

    public static String t(String key) {
        Map<String, String> table = TABLES.getOrDefault(current, TABLES.get(Language.EN_US));
        String value = table.get(key);
        if (value != null) {
            return value;
        }
        return TABLES.get(Language.EN_US).getOrDefault(key, key);
    }

    public static String t(String key, Object... args) {
        return String.format(t(key), args);
    }

    public static String translate(String key) {
        return t(key);
    }

    public static String translate(String key, Object... args) {
        return t(key, args);
    }

    public static String setting(String name) {
        return t("setting." + name);
    }

    public static String value(String name) {
        return t("value." + name);
    }

    public static String category(String name) {
        return t("gui.category." + name.toLowerCase());
    }

    public static String module(String name) {
        return t("module." + name);
    }

    public static void syncFromClientSetting() {
        if (ClientSetting.INSTANCE != null && ClientSetting.INSTANCE.language != null) {
            current = ClientSetting.INSTANCE.language.getValue();
            if (Gatopera.CONFIG != null) {
                Gatopera.CONFIG.settingsPut("language", current.getCode());
            }
        }
    }
